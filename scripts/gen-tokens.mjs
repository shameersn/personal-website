// Generates src/styles/tokens.css from brand/tokens.json
import { readFileSync, writeFileSync } from 'node:fs';

const t = JSON.parse(readFileSync('brand/tokens.json', 'utf8'));
const out = [];
out.push('/* Generated by scripts/gen-tokens.mjs from brand/tokens.json. Do not edit by hand. */');
out.push(':root {');
for (const c of t.color.tokens) out.push(`  --${c.name}: ${c.value.light};`);
out.push('');
out.push('  /* Dark values, used only inside night bands (CTA and footer) */');
for (const c of t.color.tokens) out.push(`  --${c.name}-on-night: ${c.value.dark};`);
out.push('');
out.push(`  --font-sans: ${t.type.families.sans};`);
out.push(`  --font-mono: ${t.type.families.mono};`);
for (const g of t.type.groups) for (const s of g.styles) {
  out.push(`  --${s.name}-size: ${s.fontSize};`);
  out.push(`  --${s.name}-line: ${s.lineHeight};`);
  out.push(`  --${s.name}-weight: ${s.fontWeight};`);
  if (s.letterSpacing) out.push(`  --${s.name}-tracking: ${s.letterSpacing};`);
}
out.push('');
for (const s of t.spacing.tokens) out.push(`  --${s.name}: ${s.value};`);
for (const r of t.radius.tokens) out.push(`  --${r.name}: ${r.value};`);
out.push('  --container: 1200px;');
out.push('}');
writeFileSync('src/styles/tokens.css', out.join('\n') + '\n');
